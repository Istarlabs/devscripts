"""Localized strings in one place: add, update and remove keys across JSON, Designer and .resx.

A user-facing string lives in three files, and touching only some of them is how the build breaks or
a language goes missing:

  1. Scripts/translations/{Area}.json - the source every .resx is generated from
  2. {Area}.Designer.cs - the accessors, which gen_resx.py does not touch
  3. the .resx files themselves - regenerated here by calling gen_resx.py

Usage:

    python3 Scripts/translations.py add OrderResources --from new-keys.json
    cat new-keys.json | python3 Scripts/translations.py add OrderResources
    python3 Scripts/translations.py update OrderResources --from changed-keys.json
    python3 Scripts/translations.py remove OrderResources OldKey AnotherOldKey
    python3 Scripts/translations.py new-area ActivityActionResources [--folder Enums]
    python3 Scripts/translations.py areas
    python3 Scripts/translations.py status [de] [--list]
    python3 Scripts/translations.py mark-current [de]

Input for add and update is a JSON object of key -> {lang: text}:

    {
      "StockAsNeededHint": {
        "en": "As needed - reach cannot be predicted",
        "de": "Bei Bedarf - Reichweite nicht vorhersagbar",
        ...
      }
    }

Only the base language is required, and only by `add`; `update` keeps every language it is not given.
A language that lacks a key falls back to the base text at runtime. A translation has to use the same
{0}, {1} placeholders as the base text.

Outdated translations. Scripts/translations/translated-from/{lang}.json records, per key, a short hash
of the base text a translation was made from. `add` and `update` write it for the languages they are
given, so a base text changed without them leaves those translations outdated - `status` names them.
No record means nothing is known, not that the translation is outdated. `mark-current` records the
current base text for translations that have none yet, which is how a project starts tracking.

The three verbs refuse the wrong situation instead of doing something surprising: `add` will not
overwrite an existing key (a typo in a key name must not silently replace a different string),
`update` will not create a missing one (same typo, other direction), and `remove` will not drop a key
the source still uses - pass --force when the callers really are gone.
"""
import argparse
import collections
import hashlib
import json
import os
import re
import subprocess
import sys
from pathlib import Path

from project import project

SCRIPTS = str(project.root / "Scripts")
REPO = str(project.root)
TRANSLATIONS = os.path.join(SCRIPTS, "translations")
RESOURCES = str(project.require_path("localization.resources_project"))
NAMESPACE = project.get("localization.namespace",
                        os.path.basename(RESOURCES))

from gen_resx import BASE_LANG, SATELLITE_LANGS, area_dir  # noqa: E402  - single source of truth for languages and folders

LANGUAGES = [BASE_LANG] + SATELLITE_LANGS

TRANSLATED_FROM = os.path.join(TRANSLATIONS, "translated-from")

# {0}, {1:N2}, {2,5} - the composite-format items string.Format fills. "{{" and "}}" are literal braces.
PLACEHOLDER = re.compile(r"(?<!\{)\{(\d+)(?:[,:][^{}]*)?\}")

# Where a key could still be referenced. The resources project itself is skipped: its Designer and
# .resx files mention every key by definition. Migrations are skipped for the same reason from the
# other side: they are generated, git-ignored history, and they name every database column - a key
# that happens to share a column's name ("DurationMinutes") would look referenced forever.
SOURCE_SUFFIXES = (".cs", ".razor")
SKIPPED_DIRECTORIES = {"bin", "obj", ".git", "node_modules", "Data", "Migrations"}

# The area a new one clones its .resx header from. Any of them would do - they are identical.
TEMPLATE_AREA = project.get("localization.template_area", "SharedResources")

DESIGNER_TEMPLATE = """//------------------------------------------------------------------------------
// <auto-generated>
//     This code was generated by a tool.
//
//     Changes to this file may cause incorrect behavior and will be lost if
//     the code is regenerated.
// </auto-generated>
//------------------------------------------------------------------------------

namespace {NAMESPACE} {
    using System;


    [System.CodeDom.Compiler.GeneratedCodeAttribute("System.Resources.Tools.StronglyTypedResourceBuilder", "17.0.0.0")]
    [System.Diagnostics.DebuggerNonUserCodeAttribute()]
    [System.Runtime.CompilerServices.CompilerGeneratedAttribute()]
    public class {AREA} {

        private static System.Resources.ResourceManager resourceMan;

        private static System.Globalization.CultureInfo resourceCulture;

        [System.Diagnostics.CodeAnalysis.SuppressMessageAttribute("Microsoft.Performance", "CA1811:AvoidUncalledPrivateCode")]
        internal {AREA}() {
        }

        [System.ComponentModel.EditorBrowsableAttribute(System.ComponentModel.EditorBrowsableState.Advanced)]
        public static System.Resources.ResourceManager ResourceManager {
            get {
                if (object.Equals(null, resourceMan)) {
                    System.Resources.ResourceManager temp = new System.Resources.ResourceManager("{BASENAME}.{AREA}", typeof({AREA}).Assembly);
                    resourceMan = temp;
                }
                return resourceMan;
            }
        }

        [System.ComponentModel.EditorBrowsableAttribute(System.ComponentModel.EditorBrowsableState.Advanced)]
        public static System.Globalization.CultureInfo Culture {
            get {
                return resourceCulture;
            }
            set {
                resourceCulture = value;
            }
        }

    }
}
"""


def area_path(area):
    path = os.path.join(TRANSLATIONS, f"{area}.json")

    if not os.path.exists(path):
        available = sorted(name[:-5] for name in os.listdir(TRANSLATIONS) if name.endswith(".json"))
        raise SystemExit(f"Unknown area '{area}'. Available:\n  " + "\n  ".join(available))

    return path


def load_area(area):
    with open(area_path(area), encoding="utf-8") as handle:
        return json.load(handle, object_pairs_hook=collections.OrderedDict)


def save_area(area, keys):
    with open(area_path(area), "w", encoding="utf-8") as handle:
        json.dump(keys, handle, ensure_ascii=False, indent=2)
        handle.write("\n")


def area_names():
    return sorted(name[:-5] for name in os.listdir(TRANSLATIONS) if name.endswith(".json"))


def base_hash(text):
    """What a translation records as its source. Eight hex digits of SHA-256: the translation editor
    computes the same, and a collision only costs one outdated translation going unnoticed."""
    return hashlib.sha256(text.encode("utf-8")).hexdigest()[:8]


def placeholders(text):
    return sorted(set(PLACEHOLDER.findall(text)))


def translated_from_path(language):
    return os.path.join(TRANSLATED_FROM, f"{language}.json")


def load_translated_from(language):
    path = translated_from_path(language)

    if not os.path.exists(path):
        return collections.OrderedDict()

    with open(path, encoding="utf-8") as handle:
        return json.load(handle, object_pairs_hook=collections.OrderedDict)


def save_translated_from(language, records):
    os.makedirs(TRANSLATED_FROM, exist_ok=True)
    ordered = collections.OrderedDict((area, records[area]) for area in sorted(records) if records[area])

    with open(translated_from_path(language), "w", encoding="utf-8") as handle:
        json.dump(ordered, handle, ensure_ascii=False, indent=2)
        handle.write("\n")


def record_translated_from(area, entries):
    """Note, per language, which base text these translations were made from."""
    for language in SATELLITE_LANGS:
        keys = {key: base_hash(entry[BASE_LANG]) for key, entry in entries.items() if entry.get(language)}

        if not keys:
            continue

        records = load_translated_from(language)
        records.setdefault(area, collections.OrderedDict()).update(keys)
        save_translated_from(language, records)


def load_payload(path):
    raw = sys.stdin.read() if path is None else Path(path).read_text(encoding="utf-8")

    if not raw.strip():
        raise SystemExit("No input. Pass --from <file> or pipe JSON on stdin.")

    return json.loads(raw, object_pairs_hook=collections.OrderedDict)


def validate(payload, existing, verb):
    problems = []

    for key, translations in payload.items():
        if not isinstance(translations, dict):
            problems.append(f"{key}: expected an object of language -> text")
            continue

        if verb == "add" and key in existing:
            problems.append(f"{key}: already exists (use 'update' to change it)")

        if verb == "update" and key not in existing:
            problems.append(f"{key}: does not exist (use 'add' to create it)")

        if verb == "add" and not translations.get(BASE_LANG):
            problems.append(f"{key}: missing {BASE_LANG}")

        base = translations.get(BASE_LANG) or existing.get(key, {}).get(BASE_LANG, "")

        for language in SATELLITE_LANGS:
            text = translations.get(language)

            if text and placeholders(text) != placeholders(base):
                problems.append(f"{key}: {language} uses placeholders {placeholders(text)}, "
                                f"{BASE_LANG} uses {placeholders(base)}")

        # "comment" is not a language: gen_resx.py writes it into every generated file as the
        # <comment> a translator reads, and it is where a string with {0}/{1} placeholders says what
        # they stand for. Refusing it here meant the one field that explains a format string could
        # only be added by editing the JSON by hand.
        unknown = [language for language in translations
                   if language not in LANGUAGES and language != "comment"]

        if unknown:
            problems.append(f"{key}: unknown language(s) {', '.join(unknown)}")

    if problems:
        raise SystemExit("Refusing to write:\n  " + "\n  ".join(problems))


def designer_path(area):
    return os.path.join(area_dir(area), f"{area}.Designer.cs")


def add_accessors(area, keys):
    """Append the property accessors gen_resx.py does not generate."""
    path = designer_path(area)

    if not os.path.exists(path):
        print(f"  ! {os.path.basename(path)} not found - add the accessors yourself")
        return []

    with open(path, encoding="utf-8-sig") as handle:
        content = handle.read()

    added = [key for key in keys if f'GetString("{key}"' not in content]

    if not added:
        return []

    block = "".join(
        f"        public static string {key} {{\n"
        f"            get {{\n"
        f'                return ResourceManager.GetString("{key}", resourceCulture);\n'
        f"            }}\n"
        f"        }}\n\n"
        for key in added)

    # Insert before the final closing braces of class and namespace.
    marker = "    }\n}"
    index = content.rindex(marker)

    with open(path, "w", encoding="utf-8-sig") as handle:
        handle.write(content[:index] + block + content[index:])

    return added


def remove_accessors(area, keys):
    """Drop the accessors again. The generator only ever appends, so this is the other half."""
    path = designer_path(area)

    if not os.path.exists(path):
        return []

    with open(path, encoding="utf-8-sig") as handle:
        content = handle.read()

    removed = []

    for key in keys:
        # A Designer.cs written by Visual Studio puts a doc comment above every accessor; left behind it
        # would end up in front of the next member and, for the last one, break the file.
        pattern = re.compile(
            r"(?:\n[ \t]*/// <summary>\n(?:[ \t]*///[^\n]*\n)*?[ \t]*/// </summary>[ \t]*)?"
            r"\n[ \t]*public static string " + re.escape(key) + r" \{\n"
            r"[ \t]*get \{\n"
            r"[ \t]*return ResourceManager\.GetString\(\"" + re.escape(key) + r"\", resourceCulture\);\n"
            r"[ \t]*\}\n"
            r"[ \t]*\}\n")
        content, count = pattern.subn("", content)

        if count:
            removed.append(key)

    with open(path, "w", encoding="utf-8-sig") as handle:
        handle.write(content)

    return removed


def find_references(area, keys):
    """Files still naming one of these keys, so a removal cannot quietly break a page."""
    wanted = {key: [] for key in keys}
    pattern = re.compile(r"\b(" + "|".join(re.escape(key) for key in keys) + r")\b")

    for root, directories, files in os.walk(REPO):
        directories[:] = [d for d in directories if d not in SKIPPED_DIRECTORIES]

        # The resources project names every key by definition.
        if os.path.abspath(root).startswith(RESOURCES):
            continue

        for name in files:
            if not name.endswith(SOURCE_SUFFIXES):
                continue

            path = os.path.join(root, name)

            with open(path, encoding="utf-8", errors="ignore") as handle:
                for match in pattern.finditer(handle.read()):
                    wanted[match.group(1)].append(os.path.relpath(path, REPO))

    return {key: sorted(set(paths)) for key, paths in wanted.items() if paths}


def regenerate():
    subprocess.run([sys.executable, os.path.join(SCRIPTS, "gen_resx.py")], check=True,
                   stdout=subprocess.DEVNULL)
    print("resx regenerated")


def write_keys(arguments, verb):
    existing = load_area(arguments.area)
    payload = load_payload(arguments.source)

    validate(payload, existing, verb)

    for key, translations in payload.items():
        # A language the payload leaves out keeps what it had; a base text changed without it is what
        # makes that translation outdated.
        merged = {**existing.get(key, {}), **{language: text for language, text in translations.items() if text}}
        entry = collections.OrderedDict(
            (language, merged[language]) for language in LANGUAGES if merged.get(language))

        # Carried through rather than dropped: gen_resx.py turns it into the <comment> of every
        # generated file, and a string with {0}/{1} placeholders is unreadable to a translator
        # without one. Keeping an existing comment when the update does not restate it means a
        # translation fix cannot silently strip the explanation.
        comment = translations.get("comment") or existing.get(key, {}).get("comment")

        if comment:
            entry["comment"] = comment

        existing[key] = entry

    save_area(arguments.area, existing)
    print(f"{len(payload)} key(s) written to translations/{arguments.area}.json")

    record_translated_from(arguments.area, {
        key: {BASE_LANG: existing[key][BASE_LANG],
              **{language: text for language, text in payload[key].items() if language in SATELLITE_LANGS}}
        for key in payload})

    added = add_accessors(arguments.area, list(payload))
    print(f"{len(added)} accessor(s) added to {arguments.area}.Designer.cs")

    regenerate()


def remove_keys(arguments):
    existing = load_area(arguments.area)
    unknown = [key for key in arguments.keys if key not in existing]

    if unknown:
        raise SystemExit(f"Unknown key(s) in {arguments.area}: {', '.join(unknown)}")

    if not arguments.force:
        references = find_references(arguments.area, arguments.keys)

        if references:
            lines = [f"{key}: {', '.join(paths)}" for key, paths in references.items()]
            raise SystemExit("Still referenced - remove the callers first, or pass --force:\n  "
                             + "\n  ".join(lines))

    for key in arguments.keys:
        del existing[key]

    save_area(arguments.area, existing)
    print(f"{len(arguments.keys)} key(s) removed from translations/{arguments.area}.json")

    for language in SATELLITE_LANGS:
        records = load_translated_from(language)

        if arguments.area in records:
            for key in arguments.keys:
                records[arguments.area].pop(key, None)

            save_translated_from(language, records)

    removed = remove_accessors(arguments.area, arguments.keys)
    print(f"{len(removed)} accessor(s) removed from {arguments.area}.Designer.cs")

    regenerate()


def create_area(arguments):
    """Bring a new resource area into existence, empty but complete.

    An area is four things that have to agree: the JSON source, a base .resx for gen_resx.py to clone
    its header from, a Designer.cs for the accessors to be appended to, and an ItemGroup in the
    resources .csproj that nests the satellites and runs the generator. Doing that by hand is twenty
    lines of XML that nobody remembers, and `add` refuses an area that does not exist yet - so this is
    the step that used to happen in a scratchpad.
    """
    area = arguments.area

    if not area.endswith("Resources"):
        raise SystemExit(f"'{area}' should end in 'Resources' - every existing area does")

    folder = os.path.join(RESOURCES, arguments.folder) if arguments.folder else RESOURCES
    json_path = os.path.join(TRANSLATIONS, f"{area}.json")
    resx_path = os.path.join(folder, f"{area}.resx")
    designer = os.path.join(folder, f"{area}.Designer.cs")

    for path in (json_path, resx_path, designer):
        if os.path.exists(path):
            raise SystemExit(f"Refusing to write: {os.path.relpath(path, REPO)} already exists")

    os.makedirs(folder, exist_ok=True)
    os.makedirs(TRANSLATIONS, exist_ok=True)

    with open(json_path, "w", encoding="utf-8") as handle:
        handle.write("{}\n")

    # The header is identical in every area and carries the resx schema; clone it rather than
    # reproducing 40 lines of XSD here that would then drift.
    with open(os.path.join(area_dir(TEMPLATE_AREA), f"{TEMPLATE_AREA}.resx"), encoding="utf-8") as handle:
        template = handle.read()

    header = template[:template.index("\n", template.rindex("</resheader>")) + 1]

    with open(resx_path, "w", encoding="utf-8") as handle:
        handle.write(header + "</root>\n")

    with open(designer, "w", encoding="utf-8-sig") as handle:
        handle.write(DESIGNER_TEMPLATE.replace("{NAMESPACE}", NAMESPACE).replace("{BASENAME}", manifest_base_name(folder))
                     .replace("{AREA}", area))

    add_csproj_group(area, folder)

    print(f"area {area} created - add keys with:\n"
          f"  python3 Scripts/translations.py add {area} --from keys.json")


def manifest_base_name(folder):
    """The name the compiler gives an embedded resource: the namespace, then the folders it sits in.

    The class keeps the plain namespace, so no caller changes when areas are grouped into folders;
    only the ResourceManager has to be told where the compiler put the resource.
    """
    relative = os.path.relpath(os.path.abspath(folder), os.path.abspath(RESOURCES))

    if relative == ".":
        return NAMESPACE

    return NAMESPACE + "." + relative.replace(os.sep, ".")


def resources_csproj():
    """The .csproj the resource files belong to: in their folder, or the nearest one above it.

    A project may keep its .resx in a subfolder (App.Resources/Resources/), so the project
    file is not always named after the folder the resources sit in.
    """
    folder = os.path.abspath(RESOURCES)

    while True:
        found = sorted(f for f in os.listdir(folder) if f.endswith(".csproj"))
        if found:
            return os.path.join(folder, found[0])
        parent = os.path.dirname(folder)
        if parent == folder or not parent.startswith(str(project.root)):
            raise SystemExit(f"no .csproj at or above {os.path.relpath(RESOURCES, REPO)}")
        folder = parent


def add_csproj_group(area, folder):
    """Append the area's ItemGroup, after the last one that is already there."""
    path = resources_csproj()

    with open(path, encoding="utf-8") as handle:
        content = handle.read()

    # Items are named relative to the project file; the area may sit in a subfolder of it.
    relative = os.path.relpath(os.path.abspath(folder), os.path.dirname(path))
    prefix = "" if relative == "." else relative.replace("/", "\\") + "\\"

    satellites = "".join(
        f'        <EmbeddedResource Update="{prefix}{area}.{language}.resx">\n'
        f"            <DependentUpon>{area}.resx</DependentUpon>\n"
        f"        </EmbeddedResource>\n"
        for language in LANGUAGES if language != BASE_LANG)

    group = (f'    <ItemGroup Label="{area}">\n'
             f'        <EmbeddedResource Update="{prefix}{area}.resx">\n'
             f"            <Generator>PublicResXFileCodeGenerator</Generator>\n"
             f"            <LastGenOutput>{area}.Designer.cs</LastGenOutput>\n"
             f"        </EmbeddedResource>\n"
             f'        <Compile Update="{prefix}{area}.Designer.cs">\n'
             f"            <DesignTime>True</DesignTime>\n"
             f"            <AutoGen>True</AutoGen>\n"
             f"            <DependentUpon>{area}.resx</DependentUpon>\n"
             f"        </Compile>\n"
             f"{satellites}"
             f"    </ItemGroup>\n\n")

    # After the last resource ItemGroup, which is the one before the PackageReference group. A
    # resources project that references no package has no such group; the end of the file is then
    # the same place.
    marker = "    <ItemGroup>\n        <PackageReference"
    index = content.find(marker)

    if index == -1:
        index = content.rindex("</Project>")

    with open(path, "w", encoding="utf-8") as handle:
        handle.write(content[:index] + group + content[index:])


def list_areas(_arguments):
    for name in sorted(f[:-5] for f in os.listdir(TRANSLATIONS) if f.endswith(".json")):
        keys = load_area(name)
        print(f"{name:40} {len(keys):5} key(s)")


def find_keys(arguments):
    pattern = arguments.pattern.lower()
    areas = [arguments.area] if arguments.area else sorted(
        f[:-5] for f in os.listdir(TRANSLATIONS) if f.endswith(".json"))
    hits = 0

    for area in areas:
        for key, languages in load_area(area).items():
            # The files carry "// section" comment entries whose value is a plain string.
            if not isinstance(languages, dict):
                continue

            text = languages.get(arguments.lang, "")

            if pattern not in key.lower() and not (arguments.text and pattern in text.lower()):
                continue

            print(f"{area}.{key}\n    {arguments.lang}: {text}")
            hits += 1

    if hits == 0:
        raise SystemExit(f"No key matches '{arguments.pattern}'.")


def keyed_entries(area):
    """The translatable entries of an area, without its "// Section" markers."""
    return [(key, value) for key, value in load_area(area).items() if isinstance(value, dict)]


def show_status(arguments):
    languages = arguments.languages or SATELLITE_LANGS
    unknown = [language for language in languages if language not in SATELLITE_LANGS]

    if unknown:
        raise SystemExit(f"Unknown language(s): {', '.join(unknown)}. Configured: {', '.join(SATELLITE_LANGS)}")

    problems = []
    missing = {language: [] for language in languages}
    outdated = {language: [] for language in languages}
    records = {language: load_translated_from(language) for language in languages}

    for area in area_names():
        for key, value in keyed_entries(area):
            name = f"{area}.{key}"
            base = value.get(BASE_LANG)

            if not base:
                problems.append(f"{name}: missing {BASE_LANG}")
                continue

            strange = [language for language in value if language not in LANGUAGES and language != "comment"]

            if strange:
                problems.append(f"{name}: unknown language(s) {', '.join(strange)}")

            for language in languages:
                text = value.get(language)

                if not text:
                    missing[language].append(name)
                    continue

                if placeholders(text) != placeholders(base):
                    problems.append(f"{name}: {language} uses placeholders {placeholders(text)}, "
                                    f"{BASE_LANG} uses {placeholders(base)}")

                recorded = records[language].get(area, {}).get(key)

                if recorded is not None and recorded != base_hash(base):
                    outdated[language].append(name)

    for language in languages:
        print(f"{language:6} {len(missing[language]):5} missing  {len(outdated[language]):5} outdated")

        if arguments.list:
            for name in missing[language]:
                print(f"         missing   {name}")

            for name in outdated[language]:
                print(f"         outdated  {name}")

    if problems:
        raise SystemExit("Invalid entries:\n  " + "\n  ".join(problems))


def mark_current(arguments):
    """Record the current base text for translations that have no record yet.

    Starting to track is the case this is for: until then nothing says which base text a translation
    was made from, and this says "the one there now". --overwrite also resets translations that are
    outdated, for a review that found them still correct - so it is never the default.
    """
    languages = arguments.languages or SATELLITE_LANGS

    for language in languages:
        records = load_translated_from(language)
        marked = 0

        for area in area_names():
            area_records = records.setdefault(area, collections.OrderedDict())

            for key, value in keyed_entries(area):
                if not value.get(language) or not value.get(BASE_LANG):
                    continue

                if key in area_records and not arguments.overwrite:
                    continue

                current = base_hash(value[BASE_LANG])

                if area_records.get(key) != current:
                    area_records[key] = current
                    marked += 1

        save_translated_from(language, records)
        print(f"{language}: {marked} translation(s) marked current")


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    commands = parser.add_subparsers(dest="command", required=True)

    for verb, help_text in (("add", "Create new keys"), ("update", "Change existing keys")):
        command = commands.add_parser(verb, help=help_text)
        command.add_argument("area", help='Resource area, e.g. "OrderResources"')
        command.add_argument("--from", dest="source", help="JSON file to read (default: stdin)")

    command = commands.add_parser("remove", help="Delete keys from JSON, Designer and .resx")
    command.add_argument("area", help='Resource area, e.g. "OrderResources"')
    command.add_argument("keys", nargs="+", help="Keys to delete")
    command.add_argument("--force", action="store_true",
                         help="Delete even though the source still references the key")

    command = commands.add_parser("new-area", help="Create an empty area: JSON, resx, Designer, csproj")
    command.add_argument("area", help='Resource area, e.g. "ActivityActionResources"')
    command.add_argument("--folder", help="Subfolder of the resources project to create it in (default: its root)")

    commands.add_parser("areas", help="List the resource areas and how many keys each holds")

    command = commands.add_parser("status", help="Missing and outdated translations per language")
    command.add_argument("languages", nargs="*", help="Default: every satellite language")
    command.add_argument("--list", action="store_true", help="Name the keys, not just count them")

    command = commands.add_parser("mark-current",
                                  help="Record the current base text for translations without a record")
    command.add_argument("languages", nargs="*", help="Default: every satellite language")
    command.add_argument("--overwrite", action="store_true",
                         help="Also reset outdated translations - only after reviewing them")

    command = commands.add_parser("find", help="Search keys (and optionally their text) across areas")
    command.add_argument("pattern", help="Substring to look for, case-insensitive")
    command.add_argument("--area", help="Restrict to one area (default: all)")
    command.add_argument("--lang", default="en", help="Language to print (default: en)")
    command.add_argument("--text", action="store_true", help="Match the text as well as the key")

    arguments = parser.parse_args()

    if arguments.command in ("add", "update"):
        write_keys(arguments, arguments.command)
    elif arguments.command == "remove":
        remove_keys(arguments)
    elif arguments.command == "new-area":
        create_area(arguments)
    elif arguments.command == "find":
        find_keys(arguments)
    elif arguments.command == "status":
        show_status(arguments)
    elif arguments.command == "mark-current":
        mark_current(arguments)
    else:
        list_areas(arguments)


