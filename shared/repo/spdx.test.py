"""Checks which files spdx.py wants the licence lines in. Run after touching it:

    python3 ~/dev/tools/devscripts/shared/repo/spdx.test.py
"""

import importlib.util
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
CHECKOUT = os.path.dirname(os.path.dirname(HERE))

# Importing the module looks up its project; this checkout carries its own Scripts/project.toml.
os.environ.setdefault("DEVSCRIPTS_PROJECT", CHECKOUT)
sys.path[:0] = [CHECKOUT, *(entry.path for entry in os.scandir(os.path.dirname(HERE)) if entry.is_dir())]

spec = importlib.util.spec_from_file_location("spdx", os.path.join(HERE, "spdx.py"))
spdx = importlib.util.module_from_spec(spec)
spec.loader.exec_module(spdx)

shim = '#!/usr/bin/env python3\n"""Shim: the real rpm.py lives in the shared devscripts checkout.\n\n' \
       'Generated by devscripts/install.py - the values this project differs by are in project.toml.\n"""\n'
source = "#!/usr/bin/env python3\nprint('hello')\n"
licensed = "# SPDX-FileCopyrightText: 2026 X\n# SPDX-License-Identifier: MIT\n" + source

# A shim is install.py's output: neither check nor apply may want a header in it, or the two scripts take
# turns changing it.
assert not spdx.needs_licence(shim)
assert spdx.needs_licence(source)
assert not spdx.needs_licence(licensed)

# relicense rewrites the comment line only, never a string that quotes the tag.
fixture = 'licensed = "# SPDX-License-Identifier: MIT\\n" + source\n'
header = "# SPDX-License-Identifier: AGPL-3.0-or-later\n"
assert spdx.LICENCE_LINE.sub(lambda m: m[1] + "MIT", header + fixture) == "# SPDX-License-Identifier: MIT\n" + fixture

print("ok")
