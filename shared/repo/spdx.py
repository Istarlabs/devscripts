"""
Keep the SPDX licence lines in the repository's own source files.

    python3 Scripts/spdx.py check    list the files without them; exit 1 when there are any
    python3 Scripts/spdx.py apply    add them where they are missing
    python3 Scripts/spdx.py relicense [ID]
                                     switch every file to another licence; without an ID, pick from a list

A file whose header still says "Copyright (C) <year>" gets the two SPDX lines in place of that line,
keeping its year. Any other file gets them as its first lines - after a shebang, the #: directives
of a single-file C# script, or the `<?php` line, which have to stay on top.

relicense, after one confirmation, switches the whole project: the SPDX-License-Identifier line of every
file (added where missing), spdx.licence in Scripts/project.toml, and LICENSE.md, whose text comes from
the SPDX licence list. The git history is the record of what changed.

Left alone: whatever spdx.exclude in Scripts/project.toml names - vendored code, which carries its
own licence, and output a tool rewrites - plus generated files by suffix. .razor and .css files are
covered by LICENSE.md alone.

    [spdx]
    holder = "The Something Contributors"
    licence = "AGPL-3.0-or-later"
    exclude = ["Something/wwwroot/lib/", "Scripts/dump/"]
"""

import argparse
import codecs
import datetime
import os
import re
import sys
import urllib.request

import repo
from project import project

REPO = str(project.root)

HOLDER = project.require("spdx.holder")
LICENCE = project.get("spdx.licence", "AGPL-3.0-or-later")

# Offered by `relicense` when no ID is given; any other SPDX identifier can be typed in.
LICENCES = ["AGPL-3.0-or-later", "GPL-3.0-or-later", "LGPL-3.0-or-later", "MPL-2.0", "Apache-2.0",
            "MIT", "BSD-2-Clause", "BSD-3-Clause", "ISC", "Unlicense", "CC0-1.0"]

COMMENT = {".cs": "//", ".js": "//", ".py": "#", ".sh": "#", ".sql": "--",
           ".cpp": "//", ".cc": "//", ".cxx": "//", ".h": "//", ".hpp": "//", ".hxx": "//",
           ".qml": "//", ".cmake": "#", ".rs": "//", ".ts": "//", ".php": "//"}

# Files whose name carries the type instead of the suffix. CMakeLists.txt cannot go in COMMENT:
# that would claim every .txt file in the repository.
COMMENT_BY_NAME = {"CMakeLists.txt": "#"}

EXCLUDED_PREFIXES = tuple(project.get("spdx.exclude", []))

EXCLUDED_SUFFIXES = tuple(project.get("spdx.exclude_suffixes",
                                      [".Designer.cs", ".g.cs", ".min.js"]))

# Only a line near the top counts as the header; the longest header region here ends well before this.
HEADER_LINES = 30

COPYRIGHT = re.compile(r"^(?P<prefix>//|--|#)[ \t]*Copyright \(C\)[ \t]*(?P<year>\d{4})[^\r\n]*$", re.MULTILINE)
CREATED = re.compile(r"Created[ \t]+(?P<year>\d{4})")


def comment_prefix(path):
    """How a comment starts in this file, or None when the type is not one we touch."""
    by_name = COMMENT_BY_NAME.get(os.path.basename(path))

    return by_name if by_name else COMMENT.get(os.path.splitext(path)[1])


def source_files():
    """The repository's own files of the handled types, tracked or new; ignored ones are left out."""
    for path in repo.working_files():
        if (comment_prefix(path) is not None
                and not path.startswith(EXCLUDED_PREFIXES)
                and not path.endswith(EXCLUDED_SUFFIXES)):
            yield path


def load(path):
    """The byte-order mark, if the file had one, and the text - bytes that are not UTF-8 survive a round trip."""
    with open(os.path.join(REPO, path), "rb") as handle:
        raw = handle.read()

    bom = raw.startswith(codecs.BOM_UTF8)

    return bom, raw[len(codecs.BOM_UTF8) if bom else 0:].decode("utf-8", errors="surrogateescape")


def save(path, bom, text):
    with open(os.path.join(REPO, path), "wb") as handle:
        handle.write((codecs.BOM_UTF8 if bom else b"") + text.encode("utf-8", errors="surrogateescape"))


def has_licence(text):
    return "SPDX-License-Identifier:" in "\n".join(text.splitlines()[:HEADER_LINES])


def is_generated_shim(text):
    """A shim install.py wrote: output of a tool, which the next install rewrites, so a header would not survive."""
    return "Generated by devscripts/install.py" in "\n".join(text.splitlines()[:HEADER_LINES])


def needs_licence(text):
    """Whether `check` misses the lines in this file and `apply` adds them: the one rule for both, or `apply`
    puts a header into a shim that the next install.py run takes out again."""
    return not has_licence(text) and not is_generated_shim(text)


def missing():
    """Repository-relative paths of the handled files without the licence lines."""
    return [path for path in source_files() if needs_licence(load(path)[1])]


def licence_lines(prefix, year):
    return [f"{prefix} SPDX-FileCopyrightText: {year} {HOLDER}",
            f"{prefix} SPDX-License-Identifier: {LICENCE}"]


def with_licence(path, text):
    newline = "\r\n" if "\r\n" in text else "\n"
    match = COPYRIGHT.search(text)

    if match and text.count("\n", 0, match.start()) < HEADER_LINES:
        return (text[:match.start()]
                + newline.join(licence_lines(match["prefix"], match["year"]))
                + text[match.end():])

    created = CREATED.search("\n".join(text.splitlines()[:HEADER_LINES]))
    year = created["year"] if created else str(datetime.date.today().year)

    lines = text.split(newline)
    top = 0

    while top < len(lines) and (lines[top].startswith(("#!", "#:")) or lines[top].strip() == "<?php"):
        top += 1

    # No second blank line when the file already has one right where the header goes in.
    block = licence_lines(comment_prefix(path), year) + ([] if top < len(lines) and lines[top] == "" else [""])

    return newline.join(lines[:top] + block + lines[top:])


def command_apply(_):
    changed = 0

    for path in source_files():
        bom, text = load(path)

        if not needs_licence(text):
            continue

        save(path, bom, with_licence(path, text))
        changed += 1

    print(f"added the licence lines to {changed} file(s)")

    return 0


# Only a comment line: a string in the code that quotes the tag (a test fixture) keeps its licence.
LICENCE_LINE = re.compile(r"^([ \t]*(?://|#|--)[ \t]*SPDX-License-Identifier:[ \t]*)[^\r\n]*", re.MULTILINE)


def choose_licence(given):
    """The SPDX id to switch to: the argument, or a pick from LICENCES (a number or a typed id)."""
    if given:
        return given

    if not sys.stdin.isatty():
        sys.exit("relicense needs an ID, e.g. one of: " + ", ".join(LICENCES))

    for number, name in enumerate(LICENCES, 1):
        print(f"  {number:2}  {name}{'   (current)' if name == LICENCE else ''}")

    answer = input("Licence (number or SPDX id): ").strip()

    if answer.isdigit() and 1 <= int(answer) <= len(LICENCES):
        return LICENCES[int(answer) - 1]

    return answer or sys.exit("nothing chosen")


def licence_text(name):
    """The licence text from the SPDX list, with the year and holder filled in where it has slots."""
    url = f"https://raw.githubusercontent.com/spdx/license-list-data/main/text/{name}.txt"

    try:
        with urllib.request.urlopen(url, timeout=20) as response:
            text = response.read().decode("utf-8")
    except OSError as error:
        sys.exit(f"refused: no licence text for {name} ({error}) - is it an SPDX id?")

    for slot in ("<copyright holders>", "<owner>"):
        text = text.replace(slot, HOLDER)

    return text.replace("<year>", str(datetime.date.today().year))


def set_config_licence():
    """spdx.licence in Scripts/project.toml, in place so the comments around it survive."""
    path = os.path.join(REPO, "Scripts", "project.toml")

    with open(path, encoding="utf-8") as handle:
        text = handle.read()

    line = f'licence = "{LICENCE}"'
    section = re.search(r"^\[spdx\][^\n]*\n(?:(?!\[).*\n?)*", text, re.MULTILINE)
    body = re.sub(r'^licence[ \t]*=.*$', line, section[0], flags=re.MULTILINE) if section else ""

    if section and not re.search(r'^licence[ \t]*=', section[0], flags=re.MULTILINE):
        body = section[0].rstrip("\n") + "\n" + line + "\n"

    text = text[:section.start()] + body + text[section.end():] if section else text + f"\n[spdx]\n{line}\n"

    with open(path, "w", encoding="utf-8") as handle:
        handle.write(text)


def command_relicense(arguments):
    global LICENCE

    chosen = choose_licence(arguments.licence)
    count = len(list(source_files()))

    try:
        sure = input(f"Relicense {count} file(s), Scripts/project.toml and LICENSE.md to {chosen}? Really? [y/N] ")
    except EOFError:
        sure = ""

    if sure.strip().lower() not in ("y", "yes", "j", "ja"):
        print("nothing changed")

        return 1

    text_of_licence = licence_text(chosen)
    LICENCE = chosen
    changed = 0

    for path in source_files():
        bom, text = load(path)

        if has_licence(text):
            # Only the header region, so a licence name quoted further down is not touched.
            lines = text.split("\n")
            head = LICENCE_LINE.sub(lambda m: m[1] + LICENCE, "\n".join(lines[:HEADER_LINES]))
            new = "\n".join([head] + lines[HEADER_LINES:])
        elif needs_licence(text):
            new = with_licence(path, text)
        else:
            new = text  # a generated shim: apply and check leave it without a header, so does this

        if new != text:
            save(path, bom, new)
            changed += 1

    set_config_licence()

    with open(os.path.join(REPO, "LICENSE.md"), "w", encoding="utf-8") as handle:
        handle.write(text_of_licence)

    print(f"{changed} file(s) now carry {LICENCE}; Scripts/project.toml and LICENSE.md updated")

    return 0


def command_check(_):
    found = missing()

    if not found:
        print("every source file carries the licence lines")

        return 0

    print(f"{len(found)} file(s) without the licence lines:")

    for path in found[:40]:
        print(f"  {path}")

    if len(found) > 40:
        print(f"  ... and {len(found) - 40} more")

    print("\npython3 Scripts/spdx.py apply adds them.")

    return 1


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    subparsers = parser.add_subparsers(dest="command", required=True)

    subparsers.add_parser("check", help="List files without the licence lines").set_defaults(handler=command_check)
    subparsers.add_parser("apply", help="Add the licence lines where missing").set_defaults(handler=command_apply)

    relicense = subparsers.add_parser("relicense", help="Switch every file to another licence")
    relicense.add_argument("licence", nargs="?", help="SPDX id; omitted, a list is offered")
    relicense.set_defaults(handler=command_relicense)

    arguments = parser.parse_args()

    return arguments.handler(arguments)


if __name__ == "__main__":
    sys.exit(main())
